
public class Product {
	int product_id;
	String product_name;
	String category;
	int price;
	
	public Product(int product_id, String product_name, String category, int price) {
		super();
		this.product_id = product_id;
		this.product_name = product_name;
		this.category = category;
		this.price = price;
	}

}
